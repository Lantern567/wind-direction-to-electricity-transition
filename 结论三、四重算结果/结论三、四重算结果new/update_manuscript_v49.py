def para_replace(p, old, new, tag):
    runs = list(p.runs)
    texts = [r.text for r in runs]
    full = ''.join(texts)
    assert old in full, f'{tag}: 未找到 {old[:50]!r}'
    i0 = full.index(old)
    i1 = i0 + len(old)
    pos = 0; si = None
    for k, t in enumerate(texts):
        if pos <= i0 < pos + len(t):
            si = k; break
        pos += len(t)
    assert si is not None
    prefix = texts[si][:i0 - pos]
    pos_k = pos
    last = si
    while pos_k < i1:
        pos_k += len(texts[last]); last += 1
    suffix = texts[last - 1][i1 - (pos_k - len(texts[last - 1])):] if i1 - (pos_k - len(texts[last - 1])) > 0 else ''
    runs[si].text = prefix + new + suffix
    for j in range(si + 1, last):
        runs[j].text = ''
    CHANGES.append(f'{tag}: {old[:40]}… → {new[:40]}…')
    return True

